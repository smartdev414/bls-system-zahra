// Regenerates app/dark-palette.css from Tailwind's own colour values.
//   node scripts/gen-dark-palette.mjs
// See the header comment it writes for what the file does.
import fs from "node:fs"

const css = fs.readFileSync("node_modules/tailwindcss/theme.css", "utf8")
const val = {}
for (const m of css.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) val[`${m[1]}-${m[2]}`] = m[3].trim()

const hues = ["red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan", "sky", "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose"]
const neutrals = ["slate", "gray", "zinc", "neutral", "stone"]
const all = [...hues, ...neutrals]
// var() with the stock value as fallback: Tailwind only emits the colours a page uses, and the
// colour-blind setting (globals.css) redefines the greens, which should flow through here.
const v = (h, s) => `var(--color-${h}-${s}, ${val[`${h}-${s}`]})`

const out = [
  `/* GENERATED by scripts/gen-dark-palette.mjs — edit that, not this.

   Dark theme for Tailwind's fixed palette. Pages use light tints (bg-amber-50, border-emerald-200,
   bg-violet-100 text-violet-700 …) for badges, chips and notices; on a dark page those glare as
   pale blocks. Under .dark the 50/100/200 tints become dark tints of the same hue, and dark text
   shades (600–900) become light ones. An element's own dark:text-* class still wins.
   Light-shade text (text-amber-200 on the classroom's dark panels) keeps its stock colour.
   :root.dark outranks html[data-colour-vision] in globals.css, so with colour-blind colours on,
   the greens' dark tints come out blue too. */`,
  "",
  ":root.dark {",
]
for (const h of hues) {
  out.push(`  --color-${h}-50: color-mix(in oklab, ${v(h, 900)} 28%, var(--card));`)
  out.push(`  --color-${h}-100: color-mix(in oklab, ${v(h, 900)} 42%, var(--card));`)
  out.push(`  --color-${h}-200: color-mix(in oklab, ${v(h, 700)} 55%, var(--card));`)
}
for (const h of neutrals) {
  out.push(`  --color-${h}-50: var(--muted);`, `  --color-${h}-100: var(--muted);`, `  --color-${h}-200: var(--border);`)
}
out.push("}", "")

for (const h of all) for (const s of [50, 100, 200]) out.push(`html.dark .text-${h}-${s} { color: ${val[`${h}-${s}`]}; }`)
out.push("")

const lift = { 600: 400, 700: 300, 800: 300, 900: 200 }
for (const h of all)
  for (const [s, t] of Object.entries(lift)) {
    const to = t === 200 ? val[`${h}-200`] : v(h, t)
    out.push(`html.dark .text-${h}-${s}:not([class*="dark:text-"]):not(.bg-white) { color: ${to}; }`)
  }

fs.writeFileSync("app/dark-palette.css", out.join("\n") + "\n")
console.log("wrote app/dark-palette.css")
